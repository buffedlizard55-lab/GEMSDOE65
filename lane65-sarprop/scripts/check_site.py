"""Fail closed if the published site no longer matches the committed evidence.

This is the CI half of the "obvious whether it is OK to download and submit"
requirement: if the raster's bytes, the receipt, the gate verdict and the last
site build ever disagree -- or if the promote banner were green without all three
preconditions being satisfied -- the build stops instead of publishing a stale or
over-claimed page.

What is checked about the artifact, and why it is two things
------------------------------------------------------------
The model artifact is **not** tracked in Git (the repository publication guard
forbids it), so a fresh clone has an empty ``docs/downloads/``.  The claims that
can always be verified are therefore:

1. **pixel identity** -- the committed dot list rebuilds exactly the raster's
   positive field, always checked, including when the raster is absent (it is
   rebuilt in memory);
2. **container identity** -- the raster's sha256 equals the receipt's, checked
   when the file is present.  A *difference* here is reported loudly but is not a
   failure by itself, because the documented ``--direct`` fallback legitimately
   writes the same pixels in a different container.  ``--strict-container``
   restores the hard failure for anyone verifying the actual published bytes.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
EVID = ROOT / "evidence"


def sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def pixel_report(receipt: dict, tif: pathlib.Path) -> tuple[list[str], list[str], int]:
    """Verify the artifact's information content against the committed dot list."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import numpy as np  # noqa: PLC0415
    import reconstruct_submission as rs  # noqa: PLC0415

    problems, notes = [], []
    dots = rs.load_dots(ROOT / "evidence" / "submission_dots.csv.gz")
    want = rs.field_from(dots, tuple(int(v) for v in receipt["shape"]))
    notes.append(f"dot list: {dots.shape[0]:,} positive pixels, all distinct")
    if tif.is_file():
        import rasterio  # noqa: PLC0415
        with rasterio.open(tif) as ds:
            got = ds.read(1)
            meta = {"shape": (ds.height, ds.width), "crs": ds.crs, "dtype": ds.dtypes[0]}
        if meta["shape"] != want.shape:
            problems.append(f"raster shape {meta['shape']} != dot-list grid {want.shape}")
        elif not np.array_equal(got, want):
            problems.append("raster pixels differ from the committed dot list")
        else:
            notes.append("raster pixels are exactly the committed dot list")
    else:
        notes.append(f"raster not present at {receipt['file']} (untracked by design); "
                      "pixel identity verified against the dot list only")
    return problems, notes, int(dots.shape[0])


def main() -> int:
    strict = "--strict-container" in sys.argv
    problems: list[str] = []
    notes: list[str] = []
    receipt = json.loads((EVID / "submission_receipt.json").read_text())
    tif = ROOT / receipt["file"]

    px_problems, px_notes, _ = pixel_report(receipt, tif)
    problems += px_problems
    notes += px_notes

    if tif.is_file():
        got = sha256(tif)
        if got != receipt["sha256"]:
            msg = (f"container sha256 {got[:16]}... differs from the receipt "
                   f"{receipt['sha256'][:16]}... -- this is a rebuild (identical pixels, "
                   "different container), not the published file")
            if strict:
                problems.append(msg)
            else:
                notes.append(msg + " [warning, not a failure]")
        else:
            notes.append("container sha256 matches the receipt exactly")
    zip_name = tif.with_suffix(".zip")
    if not zip_name.is_file():
        notes.append(f"single-TIFF zip not present ({zip_name.name}); generated by the build, "
                      "untracked by design")

    status = json.loads((DOCS / "status.json").read_text())
    for page in ("index.html", "executive-summary.html", "evidence.html",
                 "analysis-02778.html", "verification.html", "limitations.html"):
        if not (DOCS / page).is_file():
            problems.append(f"site page missing: {page}")

    gate = json.loads((EVID / "gate.json").read_text()).get("gate", {})
    if status.get("gate_verdict") != gate.get("verdict"):
        problems.append("status.json gate verdict disagrees with evidence/gate.json")

    green = {c["check"]: c["green"] for c in status.get("preconditions", [])}
    if status.get("ok_to_submit"):
        if not green.get("Blocked-holdout gate"):
            problems.append("site claims OK to submit while the gate check is not green")
        if not green.get("On-disk format validator"):
            problems.append("site claims OK to submit while the validator check is not green")
        if green.get("Parallel-run duplicate audit") is not True:
            problems.append("site claims OK to submit while the duplicate audit is not green")

    if problems:
        print("CHECK FAILED")
        for p in problems:
            print("  -", p)
        return 1
    for n in notes:
        print("  note:", n)
    print(f"site check OK: ok_to_submit={status.get('ok_to_submit')}, "
          f"gate={status.get('gate_verdict')}, dots={status.get('n_dots')}, "
          f"sha256={receipt['sha256'][:16]}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
